// Turns the Office Open XML preset shape definitions (ECMA-376, data/presetShapeDefinitions.xml) into
// compact JSON, gzipped and base64-encoded into src/presets-data.ts. Run: node scripts/embed-presets.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';

const xml = readFileSync(new URL('../data/presetShapeDefinitions.xml', import.meta.url), 'utf8');

// A small XML reader: the file is regular (no text content, no CDATA), so tags and attributes suffice.
function parse(src) {
  const root = { tag: '#root', at: {}, kids: [] }, stack = [root];
  const re = /<(\/?)([A-Za-z0-9:]+)((?:\s+[A-Za-z0-9:]+="[^"]*")*)\s*(\/?)>|<\?[^>]*\?>/g;
  let m;
  while ((m = re.exec(src))) {
    if (!m[2]) continue;
    if (m[1]) { stack.pop(); continue; }
    const at = {}; for (const a of m[3].matchAll(/([A-Za-z0-9:]+)="([^"]*)"/g)) if (a[1] !== 'xmlns') at[a[1]] = a[2];
    const node = { tag: m[2], at, kids: [] };
    stack[stack.length - 1].kids.push(node);
    if (!m[4]) stack.push(node);
  }
  return root.kids[0];
}

const kid = (n, tag) => n.kids.find(k => k.tag === tag);
const pt = n => { const p = kid(n, 'pt') || kid(n, 'pos'); return [p.at.x, p.at.y]; };
const num = v => (v != null && /^-?\d+(\.\d+)?$/.test(v) ? Number(v) : v);
const out = {};
for (const shape of parse(xml).kids) {
  if (out[shape.tag]) continue;
  const def = {};
  const av = kid(shape, 'avLst'), gd = kid(shape, 'gdLst'), ah = kid(shape, 'ahLst'), rect = kid(shape, 'rect'), pl = kid(shape, 'pathLst');
  if (av && av.kids.length) def.av = av.kids.map(g => [g.at.name, g.at.fmla]);
  if (gd && gd.kids.length) def.gd = gd.kids.map(g => [g.at.name, g.at.fmla]);
  if (ah && ah.kids.length) def.ah = ah.kids.map(h => {
    const a = h.at, o = { pos: pt(h) };
    if (h.tag === 'ahXY') { if (a.gdRefX) o.x = [a.gdRefX, num(a.minX), num(a.maxX)]; if (a.gdRefY) o.y = [a.gdRefY, num(a.minY), num(a.maxY)]; }
    else { if (a.gdRefR) o.r = [a.gdRefR, num(a.minR), num(a.maxR)]; if (a.gdRefAng) o.a = [a.gdRefAng, num(a.minAng), num(a.maxAng)]; }
    return o;
  });
  if (rect) def.tx = [rect.at.l, rect.at.t, rect.at.r, rect.at.b];
  def.p = (pl ? pl.kids : []).map(p => {
    const o = { c: [] };
    if (p.at.w) o.w = Number(p.at.w); if (p.at.h) o.h = Number(p.at.h);
    if (p.at.fill && p.at.fill !== 'norm') o.f = p.at.fill;
    if (p.at.stroke === 'false') o.s = 0;
    for (const c of p.kids) {
      if (c.tag === 'moveTo') o.c.push(['M', ...pt(c)].map(num));
      else if (c.tag === 'lnTo') o.c.push(['L', ...pt(c)].map(num));
      else if (c.tag === 'arcTo') o.c.push(['A', c.at.wR, c.at.hR, c.at.stAng, c.at.swAng].map(num));
      else if (c.tag === 'quadBezTo') o.c.push(['Q', ...c.kids.flatMap(k => [k.at.x, k.at.y])].map(num));
      else if (c.tag === 'cubicBezTo') o.c.push(['C', ...c.kids.flatMap(k => [k.at.x, k.at.y])].map(num));
      else if (c.tag === 'close') o.c.push(['Z']);
    }
    return o;
  });
  out[shape.tag] = def;
}
// The published file defines upDownArrow twice and upArrow not at all; upArrow is downArrow turned
// over, written here from the ECMA-376 definition.
if (!out.upArrow) out.upArrow = {
  av: [['adj1', 'val 50000'], ['adj2', 'val 50000']],
  gd: [['maxAdj2', '*/ 100000 h ss'], ['a1', 'pin 0 adj1 100000'], ['a2', 'pin 0 adj2 maxAdj2'], ['dy2', '*/ ss a2 100000'], ['y2', '+- t dy2 0'],
    ['dx1', '*/ w a1 200000'], ['x1', '+- hc 0 dx1'], ['x2', '+- hc dx1 0'], ['dy1', '*/ x1 dy2 wd2'], ['y1', '+- y2 0 dy1']],
  ah: [{ pos: ['x1', 'b'], x: ['adj1', 0, 100000] }, { pos: ['l', 'y2'], y: ['adj2', 0, 'maxAdj2'] }],
  tx: ['x1', 'y1', 'x2', 'b'],
  p: [{ c: [['M', 'l', 'y2'], ['L', 'hc', 't'], ['L', 'r', 'y2'], ['L', 'x2', 'y2'], ['L', 'x2', 'b'], ['L', 'x1', 'b'], ['L', 'x1', 'y2'], ['Z']] }],
};
const json = JSON.stringify(out);
const b64 = gzipSync(Buffer.from(json), { level: 9 }).toString('base64');
writeFileSync(new URL('../src/presets-data.ts', import.meta.url),
  `// Generated by scripts/embed-presets.mjs from data/presetShapeDefinitions.xml (ECMA-376). Do not edit.\n` +
  `export const PRESETS_GZ = '${b64}';\nexport const PRESET_COUNT = ${Object.keys(out).length};\n`);
console.log(Object.keys(out).length, 'shapes,', json.length, 'bytes of JSON,', b64.length, 'bytes embedded');
