// Turns wasm/ixops.wasm into src/ixops-wasm.ts (gzipped, base64) so the engine is built into the single HTML file.
// Shrink first with: npx wasm-opt -Oz --enable-bulk-memory --enable-sign-ext --enable-mutable-globals --enable-nontrapping-float-to-int in.wasm -o wasm/ixops.wasm
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
const src = new URL('../wasm/ixops.wasm', import.meta.url), out = new URL('../src/ixops-wasm.ts', import.meta.url);
if (!existsSync(src)) { console.error('wasm/ixops.wasm not found'); process.exit(1); }
const b64 = gzipSync(readFileSync(src), { level: 9 }).toString('base64');
writeFileSync(out, `// Generated by scripts/embed-wasm.mjs from wasm/ixops.wasm (gzip, base64). Do not edit.\nexport const WASM_B64 = '${b64}';\n`);
console.log(`embedded ${b64.length} base64 characters`);
